/**
 * Refreshes src/content/store-ratings.generated.ts from the live API so each
 * build ships accurate schema.org AggregateRating numbers (and an accurate
 * first paint) instead of numbers typed in by hand months ago.
 *
 * Runs on prebuild. It must never fail the build: if the API is unreachable,
 * slow, or returns something implausible, the committed values stay exactly
 * as they are and the build carries on.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outputFile = path.join(__dirname, "..", "src", "content", "store-ratings.generated.ts");

const apiUrl =
  process.env.STORE_RATINGS_API_URL ?? "https://api.busydadtraining.com/api/v1/StoreRatings";

const TIMEOUT_MS = 10_000;

/** Guards against writing junk if the endpoint ever returns something odd. */
function isPlausible(store) {
  return (
    store &&
    typeof store.rating === "number" &&
    Number.isFinite(store.rating) &&
    store.rating > 0 &&
    store.rating <= 5 &&
    Number.isInteger(store.ratingCount) &&
    store.ratingCount > 0
  );
}

function round(value, places) {
  return Number(value.toFixed(places));
}

function render({ apple, google, combined, app }) {
  const today = new Date().toISOString().slice(0, 10);

  return `/**
 * AUTO-GENERATED by scripts/fetch-store-ratings.mjs (runs on prebuild).
 *
 * Do not hand-edit, but do keep it committed. It serves two jobs:
 *   1. the build-time schema.org AggregateRating (client-side JSON-LD is not
 *      reliably indexed, so those numbers have to be in the HTML), and
 *   2. the fallback shown before the live API response arrives, or instead
 *      of it if the API is down.
 *
 * Source of truth at runtime: GET /api/v1/StoreRatings on the BDT API.
 */
export const generatedStoreRatings = {
  apple: { rating: ${round(apple.rating, 2)}, ratingCount: ${apple.ratingCount} },
  google: { rating: ${round(google.rating, 2)}, ratingCount: ${google.ratingCount} },
  combined: { rating: ${round(combined.rating, 2)}, ratingCount: ${combined.ratingCount} },
  app: { version: "${app.version}", updated: "${app.updated}" },
  fetchedAt: "${today}",
} as const;
`;
}

async function main() {
  let payload;

  try {
    const response = await fetch(apiUrl, {
      signal: AbortSignal.timeout(TIMEOUT_MS),
      headers: { accept: "application/json" },
    });

    if (!response.ok) throw new Error(`HTTP ${response.status}`);

    payload = (await response.json())?.data;
  } catch (error) {
    console.warn(
      `[store-ratings] Could not reach ${apiUrl} (${error.message}); keeping the committed values.`,
    );
    return;
  }

  const { apple, google, combined } = payload ?? {};

  if (!isPlausible(apple) || !isPlausible(google) || !isPlausible(combined)) {
    console.warn("[store-ratings] API response was not usable; keeping the committed values.");
    return;
  }

  // "seed" means the API itself never managed to fetch either store, so its
  // numbers are no better than the ones already committed here.
  if (combined.source === "seed") {
    console.warn("[store-ratings] API returned seed values; keeping the committed values.");
    return;
  }

  const current = await readFile(outputFile, "utf8").catch(() => "");

  // App version rides along on the same endpoint. If the API doesn't have it
  // yet (fresh process, Apple fetch failed), keep the committed values.
  const committedApp = /app: \{ version: "([^"]+)", updated: "([^"]+)" \}/.exec(current);
  const app = {
    version: payload.appVersion ?? committedApp?.[1] ?? "unknown",
    updated: payload.appUpdatedUtc?.slice(0, 10) ?? committedApp?.[2] ?? "unknown",
  };

  if (app.version === "unknown") {
    console.warn("[store-ratings] No app version available; keeping the committed values.");
    return;
  }

  const next = render({ apple, google, combined, app });

  // Compare on content minus the fetchedAt line, so an unchanged rating
  // doesn't produce a git diff on every single build.
  const withoutDate = (text) => text.replace(/^\s*fetchedAt:.*$/m, "");

  if (withoutDate(current) === withoutDate(next)) {
    console.log("[store-ratings] Ratings unchanged.");
    return;
  }

  await writeFile(outputFile, next, "utf8");

  console.log(
    `[store-ratings] Updated: App Store ${apple.rating} (${apple.ratingCount}), ` +
      `Google Play ${google.rating} (${google.ratingCount}), ` +
      `combined ${combined.rating} (${combined.ratingCount}), app v${app.version} (${app.updated}).`,
  );
}

await main();
